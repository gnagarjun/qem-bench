import { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { Dialog, DialogContent, DialogTitle, DialogDescription } from "@/components/ui/dialog";
import { API, get } from "@/lib/qem";

export default function FiguresTab() {
  const q = useQuery({ queryKey: ["figures"], queryFn: () => get("/figures") });
  const [open, setOpen] = useState(null);
  return (
    <div className="space-y-6" data-testid="figures-gallery-tab">
      <p className="text-sm text-slate-400 max-w-3xl">The 12 publication figures, generated by <code className="num">scripts/generate_figures.py</code> from the saved aggregated data. PDF versions are in the repository under <code className="num">results/figures/</code>.</p>
      <div className="grid sm:grid-cols-2 xl:grid-cols-3 gap-5">
        {(q.data || []).map((f, i) => (
          <button key={f.id} data-testid={`figure-card-${f.id}`} onClick={() => setOpen(f)} className="card overflow-hidden text-left rise group transition-colors hover:border-sky-500/40" style={{ animationDelay: `${i * 40}ms` }}>
            <div className="bg-white aspect-[4/3] flex items-center justify-center overflow-hidden">
              <img src={`${API}/figures/${f.png}`} alt={f.caption} loading="lazy" className="w-full h-full object-contain transition-transform duration-300 group-hover:scale-[1.02]" />
            </div>
            <div className="p-4"><div className="overline">Figure {i + 1}</div><p className="text-sm mt-1 text-slate-300">{f.caption}</p></div>
          </button>
        ))}
      </div>
      <Dialog open={!!open} onOpenChange={(o) => !o && setOpen(null)}>
        <DialogContent className="max-w-6xl bg-[#111622] border-white/10" data-testid="figure-zoom-modal">
          <DialogTitle className="font-display">{open?.id}</DialogTitle>
          <DialogDescription className="text-slate-400">{open?.caption}</DialogDescription>
          {open && <img src={`${API}/figures/${open.png}`} alt={open.caption} className="w-full bg-white rounded" />}
        </DialogContent>
      </Dialog>
    </div>
  );
}
